import type { PriceExam } from "./core";

/** 병원비 — 진료 전 비급여 문의 메모.
 * 비급여는 사전 설명 대상(의료법 제45조: 비급여 진료비용 고지 의무). */
export function buildHospitalMemo(name: string, exams: PriceExam[]): string {
  const top = exams.slice(0, 5);
  return [
    `${name} 진료 전 비급여 확인 메모`,
    ``,
    `병원은 비급여 진료비용을 환자가 알 수 있게 고지할 의무가 있습니다(의료법 제45조).`,
    `예약·접수 시 아래를 확인하면 예상 밖의 청구를 줄일 수 있습니다.`,
    ``,
    `1. 오늘 진료에서 비급여 항목이 예정되어 있나요? 있다면 항목과 금액을 알려주세요.`,
    ...(top.length
      ? [`2. 심사평가원 공개 기준 이 병원의 주요 비급여 가격은 다음과 같았습니다. 현재도 같은가요?`,
         ...top.map((e, i) => `   ${String.fromCharCode(0x2460 + i)} ${e.name} — 공개가 ${e.price.toLocaleString()}원`)]
      : [`2. 주요 비급여 항목의 현재 가격표를 보여주세요.`]),
    `3. 같은 목적의 급여(건강보험 적용) 대안이 있나요?`,
    ``,
    `※ 이 메모는 공개된 가격의 확인 요청이며, 진료의 적정성에 대한 판단이 아닙니다.`,
  ].join("\n");
}

/** 장례비 — 사전 확인 목록.
 * 장례식장은 임대료·수수료·장례용품 가격표 게시 의무(장사법 제29조). */
export function buildFuneralChecklist(name: string, exams: PriceExam[]): string {
  const top = exams.slice(0, 5);
  return [
    `${name} 이용 전 가격 확인 목록`,
    ``,
    `장례식장은 시설 임대료·수수료와 장례용품 가격표를 게시하고 e하늘에 등록할 의무가`,
    `있습니다(장사 등에 관한 법률 제29조). 계약 전 아래를 확인하세요.`,
    ``,
    `1. 게시된 가격표와 실제 청구 항목이 일치하는지`,
    ...(top.length
      ? [`2. e하늘 공시 기준 이 시설의 주요 가격은 다음과 같았습니다(2023.6). 현재 가격을 확인하세요.`,
         ...top.map((e, i) => `   ${String.fromCharCode(0x2460 + i)} ${e.name} — 공시가 ${e.price.toLocaleString()}원`)]
      : [`2. 빈소 사용료·안치료·염습비 등 주요 항목의 현재 가격`]),
    `3. 장례용품(수의·관 등)은 외부 반입이 가능한지, 반입 시 추가 비용이 있는지`,
    `4. 최종 견적서에 포함되지 않은 비용이 발생할 수 있는 항목`,
    ``,
    `※ 이 목록은 공시 가격의 확인 요청이며, 시설에 대한 평가가 아닙니다.`,
  ].join("\n");
}
