import type { PriceExam } from "../pricedom/core";

/**
 * 학원비편 처방전 — 교습비 확인 요청문.
 * 근거: 학원의 설립·운영 및 과외교습에 관한 법률 제15조
 * (교습비등의 게시·표시 의무, 신고한 금액 초과 징수 금지).
 * 수치·조항은 데이터에서 그대로 가져오고, 판정 표현은 쓰지 않는다.
 */
export function buildAcademyInquiry(name: string, exams: PriceExam[]): string {
  const top = exams.slice(0, 3);
  return [
    `수신  ${name} 귀중`,
    `제목  교습비등 게시 내용 확인 요청`,
    ``,
    `학원의 설립·운영 및 과외교습에 관한 법률 제15조에 따라 학원은 교습비등을`,
    `학습자가 쉽게 볼 수 있는 장소에 게시하여야 하며, 교육청에 신고한 금액을`,
    `초과하여 받을 수 없습니다. 아래 사항의 확인을 요청드립니다.`,
    ``,
    `1. 현재 게시 중인 교습비등 전체 내역 (과목별 금액·교습 시간·횟수)`,
    ...(top.length
      ? [`2. 교육청 공시 기준 아래 과목의 현재 실제 교습비`,
         ...top.map((e, i) => `   ${String.fromCharCode(0x2460 + i)} ${e.name} — 공시액 ${e.price.toLocaleString()}원`)]
      : [`2. 교육청에 신고된 교습비와 현재 받고 있는 금액의 일치 여부`]),
    `3. 교재비·재료비 등 교습비 외 추가 비용이 있는 경우 그 항목과 금액`,
    ``,
    `회신 희망일  요청일로부터 7일 이내`,
    ``,
    `※ 신고 금액을 초과해 받는 경우 관할 교육지원청에 신고할 수 있습니다.`,
  ].join("\n");
}
